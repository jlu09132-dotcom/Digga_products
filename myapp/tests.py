from django.test import TestCase
from rest_framework.test import APIClient
from rest_framework import status
from .models import Buyer, Supplier, AdminUser, Category, Product


class BuyerRegistrationTest(TestCase):
    def setUp(self):
        self.client = APIClient()

    def test_buyer_register(self):
        res = self.client.post('/api/buyers/', {
            'name': 'Test Buyer', 'email': 'buyer@test.com',
            'phone': '9876543210', 'password': 'test1234',
        }, format='json')
        self.assertEqual(res.status_code, status.HTTP_201_CREATED)

    def test_buyer_login(self):
        buyer = Buyer(name='B', email='b@b.com', phone='1234567890')
        buyer.set_password('pass1234')
        buyer.save()

        res = self.client.post('/api/login/', {'email': 'b@b.com', 'password': 'pass1234'}, format='json')
        self.assertEqual(res.status_code, status.HTTP_200_OK)
        self.assertIn('access', res.data)
        self.assertEqual(res.data['role'], 'buyer')

    def test_buyer_wrong_password(self):
        buyer = Buyer(name='B', email='bwrong@b.com', phone='1234567890')
        buyer.set_password('correct')
        buyer.save()

        res = self.client.post('/api/login/', {'email': 'bwrong@b.com', 'password': 'wrong'}, format='json')
        self.assertEqual(res.status_code, status.HTTP_401_UNAUTHORIZED)


